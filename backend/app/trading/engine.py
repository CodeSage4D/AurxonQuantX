class OrderRequest(BaseModel):
    """Pending order request generated by a strategy at Bar T decision time."""
    order_id: str = Field(default_factory=lambda: f"ORD-{uuid.uuid4().hex[:8].upper()}")
    symbol: str
    action: TradeAction
    quantity: int
    order_type: str = "MARKET"
    signal_date: str  # Bar T date
    signal_price: float  # Bar T Close
    reason: str = ""


class Position(BaseModel):
    """Open position record with FIFO tracking and mark-to-market valuation."""
    symbol: str
    quantity: int = 0
    average_cost: float = 0.0
    current_price: float = 0.0
    market_value: float = 0.0
    unrealized_pnl: float = 0.0
    unrealized_pnl_pct: float = 0.0

    def update_price(self, price: float):
        self.current_price = price
        self.market_value = round(self.quantity * price, 2)
        if self.quantity > 0 and self.average_cost > 0:
            self.unrealized_pnl = round((price - self.average_cost) * self.quantity, 2)
            self.unrealized_pnl_pct = round(((price - self.average_cost) / self.average_cost) * 100.0, 2)
        else:
            self.unrealized_pnl = 0.0
            self.unrealized_pnl_pct = 0.0


class Portfolio(BaseModel):
    """Portfolio state tracker across simulation events."""
    cash: float
    initial_capital: float
    positions: Dict[str, Position] = Field(default_factory=dict)
    total_transaction_costs_paid: float = 0.0

    def get_position(self, symbol: str) -> Position:
        if symbol not in self.positions:
            self.positions[symbol] = Position(symbol=symbol)
        return self.positions[symbol]

    def total_positions_value(self) -> float:
        return round(sum(pos.market_value for pos in self.positions.values()), 2)

    def total_equity(self) -> float:
        return round(self.cash + self.total_positions_value(), 2)


class BaseStrategy(ABC):
    """Abstract Strategy interface enforcing no-lookahead signal evaluation."""

    def __init__(self, name: str, version: str = "1.0", parameters: Optional[Dict[str, Any]] = None):
        self.name = name
        self.version = version
        self.parameters = parameters or {}

    @abstractmethod
    def on_bar(
        self,
        current_bar: HistoricalBar,
        history: List[HistoricalBar],
        portfolio: Portfolio,
    ) -> List[OrderRequest]:
        """Evaluates strategy rules strictly using data up to and including current_bar.
        Orders returned will be scheduled for execution at NEXT bar open (T+1).
        """
        pass


class DualMovingAverageStrategy(BaseStrategy):
    """Classic trend-following strategy using fast and slow moving average crossover."""

    def __init__(self, fast_period: int = 10, slow_period: int = 30, quantity: int = 10):
        super().__init__(
            name="DualMovingAverageCrossover",
            version="1.0",
            parameters={"fast_period": fast_period, "slow_period": slow_period, "quantity": quantity},
        )
        self.fast_period = fast_period
        self.slow_period = slow_period
        self.quantity = quantity

    def on_bar(
        self, current_bar: HistoricalBar, history: List[HistoricalBar], portfolio: Portfolio
    ) -> List[OrderRequest]:
        if len(history) < self.slow_period + 1:
            return []

        closes = [b.close for b in history]
        fast_now = sum(closes[-self.fast_period:]) / self.fast_period
        slow_now = sum(closes[-self.slow_period:]) / self.slow_period

        fast_prev = sum(closes[-(self.fast_period + 1):-1]) / self.fast_period
        slow_prev = sum(closes[-(self.slow_period + 1):-1]) / self.slow_period

        pos = portfolio.get_position(current_bar.symbol)
        orders = []

        # Bullish Golden Cross -> BUY
        if fast_prev <= slow_prev and fast_now > slow_now and pos.quantity == 0:
            orders.append(
                OrderRequest(
                    symbol=current_bar.symbol,
                    action=TradeAction.BUY,
                    quantity=self.quantity,
                    signal_date=current_bar.trading_date,
                    signal_price=current_bar.close,
                    reason=f"Fast SMA ({fast_now:.2f}) crossed above Slow SMA ({slow_now:.2f})",
                )
            )

        # Bearish Death Cross -> SELL
        elif fast_prev >= slow_prev and fast_now < slow_now and pos.quantity > 0:
            orders.append(
                OrderRequest(
                    symbol=current_bar.symbol,
                    action=TradeAction.SELL,
                    quantity=pos.quantity,
                    signal_date=current_bar.trading_date,
                    signal_price=current_bar.close,
                    reason=f"Fast SMA ({fast_now:.2f}) crossed below Slow SMA ({slow_now:.2f})",
                )
            )

        return orders


class BuyAndHoldStrategy(BaseStrategy):
    """Benchmark strategy buying on the first eligible bar and holding."""

    def __init__(self, quantity: int = 10):
        super().__init__(name="BuyAndHoldBenchmark", version="1.0", parameters={"quantity": quantity})
        self.quantity = quantity
        self._bought = False

    def on_bar(
        self, current_bar: HistoricalBar, history: List[HistoricalBar], portfolio: Portfolio
    ) -> List[OrderRequest]:
        pos = portfolio.get_position(current_bar.symbol)
        if not self._bought and pos.quantity == 0:
            self._bought = True
            return [
                OrderRequest(
                    symbol=current_bar.symbol,
                    action=TradeAction.BUY,
                    quantity=self.quantity,
                    signal_date=current_bar.trading_date,
                    signal_price=current_bar.close,
                    reason="Initial benchmark allocation buy",
                )
            ]
        return []


