"""AURXON Deterministic Event-Driven Backtesting Engine.
Executes reproducible historical simulations with:
- Strict chronology: Signals generated at Bar T close are executed on Bar T+1 Open.
- Absolute prevention of lookahead bias and same-bar execution leakage.
- Precise portfolio accounting: cash, positions, FIFO realized P&L, corporate actions.
- Indian market statutory transaction cost deduction (STT, exchange fees, GST, stamp duty).
- Cryptographic audit trail generation into the AURXON hash-chain ledger.
"""

